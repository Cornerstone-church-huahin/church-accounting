// ทดสอบแถวบันทึกแบบตาราง (ช่อง 1 ของ รับ และ จ่าย): เลือกรายการตามใบ → เพิ่มลงตาราง → ขึ้นเป็นตารางด้านล่าง → เข้าใบสรุป
import { chromium } from 'playwright'
import { spawn } from 'node:child_process'
import fs from 'node:fs'
const PORT = 4179
const server = spawn('npx', ['vite', 'preview', '--port', String(PORT), '--strictPort'], { stdio: 'ignore' })
await new Promise((r) => setTimeout(r, 2500))
const exe = fs.existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : undefined
const browser = await chromium.launch(exe ? { executablePath: exe } : {})
const ctx = await browser.newContext({ viewport: { width: 390, height: 800 }, locale: 'th-TH' })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
const iso = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
const sunD = new Date(); sunD.setDate(sunD.getDate() + ((7 - sunD.getDay()) % 7))
const monD = new Date(sunD); monD.setDate(sunD.getDate() - 6)
const midD = new Date(sunD); midD.setDate(sunD.getDate() - 3)
const must = (c, m) => { if (!c) throw new Error('FAIL: ' + m) }
try {
  await page.goto(`http://localhost:${PORT}/#/`)
  // ---- รับ ----
  await page.getByRole('tab', { name: /💚 รับ/ }).click()
  await page.getByRole('tab', { name: /บันทึกด้วยมือ/ }).click()
  const types = await page.locator('#mi-type option').allInnerTexts()
  must(['สิบลด', 'ประจำสัปดาห์', 'ขอบพระคุณ', 'อาหารวันอาทิตย์', 'กองทุนเพื่อที่ดินคริสตจักร', 'กองทุนสร้างอาคารพันธกิจ', 'กองทุนสุสาน'].every((n, i) => types[i] === n), 'type list follows the printed form: ' + types.join('|'))
  await page.locator('#mi-type').selectOption({ label: 'ประจำสัปดาห์' })
  await page.locator('#mi-env').fill('7')
  await page.locator('.entryrow .field', { hasText: 'เงินสด (บาท)' }).locator('input').fill('2040')
  await page.locator('#mi-tc').fill('1')
  await page.locator('.entryrow .field', { hasText: 'เงินโอน (บาท)' }).locator('input').fill('2000')
  await page.getByRole('button', { name: '＋ เพิ่มลงตาราง' }).click()
  const tbl = page.getByRole('table', { name: /ใบบันทึกการถวาย \(A4 แนวนอน\)/ })
  await tbl.waitFor()
  const t = (await tbl.innerText()).replace(/\s+/g, ' ')
  must(/1\. ประจำสัปดาห์ 7 2,040/.test(t) && /2\. ประจำสัปดาห์ 1 2,000/.test(t) && /รวมทั้งสิ้น 7 2,040 1 2,000 4,040/.test(t), 'income landscape A4 sheet rows + totals: ' + t)
  must((await tbl.locator('tbody tr').count()) === 20, 'income sheet keeps 20 locked rows')
  const head = (await page.locator('.a4page').first().innerText()).replace(/\s+/g, ' ')
  must(/ประจำวันอาทิตย์ที่ \d ของเดือน\S+ · ระหว่างวันที่ \d+(–\d+| \S+ – \d+) \S+ พ\.ศ\. 25\d\d/.test(head), 'sheet heading names the real Sunday and date range: ' + head.slice(0, 160))
  must((await page.getByRole('button', { name: /ดาวน์โหลด PDF ขนาดจริง/ }).count()) === 1, 'PDF button under the income sheet')
  must(/รวมจากตู้ถวาย 2,040 บาท/.test((await page.locator('.a4page').first().innerText()).replace(/\s+/g, ' ')), 'sheet footer shows cash total')
  await page.screenshot({ path: 'shots/entry-income.png', fullPage: true })
  await page.getByRole('tab', { name: /รวมรับ/ }).click()
  const rt = (await page.locator('.a4page').last().innerText()).replace(/\n/g, ' ')
  must(/ประจำสัปดาห์\s+7\s+2,040\.00\s+1\s+2,000\.00\s+4,040\.00/.test(rt), 'summary row from table entries: ' + rt)
  // บันทึกข้ามวัน/ย้อนวัน: ระบบเรียงวันที่ให้เอง (ต้นสัปดาห์อยู่บน)
  await page.getByRole('tab', { name: /บันทึกด้วยมือ/ }).click()
  for (const d of [sunD, monD, midD]) {
    await page.locator('#mi-date').fill(iso(d))
    await page.locator('.entryrow .field', { hasText: 'เงินสด (บาท)' }).locator('input').fill('100')
    await page.getByRole('button', { name: '＋ เพิ่มลงตาราง' }).click()
    await page.waitForTimeout(150)
  }
  const dateCells = await tbl.locator('tbody tr td:first-child').allInnerTexts()
  const filled = dateCells.filter((x) => x.trim())
  const monTxt = filled.findIndex((x) => x.startsWith(String(monD.getDate()) + ' ')), sunTxt = filled.findLastIndex((x) => x.startsWith(String(sunD.getDate()) + ' '))
  must(monTxt >= 0 && sunTxt > monTxt && monTxt < filled.findIndex((x) => x.startsWith(String(midD.getDate()) + ' ')), 'income rows are ordered by date: ' + filled.join(' | '))
  // ---- จ่าย ----
  await page.getByRole('tab', { name: /🔴 จ่าย/ }).click()
  await page.getByRole('tab', { name: /บันทึกด้วยมือ/ }).click()
  const items = await page.locator('#me-item option').allInnerTexts()
  must(items.length === 11 && items[0] === 'ค่าน้ำมันออกเยี่ยม อ.กฤต' && items[10] === 'ค่าน้ำ', 'expense list follows the voucher: ' + items.join('|'))
  await page.locator('#me-item').selectOption({ label: 'ค่าไฟ' })
  await page.locator('.entryrow .field', { hasText: 'จำนวนเงิน (บาท)' }).locator('input').fill('1850')
  await page.locator('#me-req').fill('สมเจต')
  await page.locator('#me-pay').fill('การไฟฟ้า')
  await page.getByRole('button', { name: '＋ เพิ่มลงตาราง' }).click()
  const et = page.getByRole('table', { name: /ใบเบิก-จ่ายเงินสด \(A4\)/ })
  await et.waitFor()
  const e = (await et.innerText()).replace(/\s+/g, ' ')
  must(/ผู้รับเงิน/.test(e) && /หมายเหตุ/.test(e) && !/ผู้เบิกเงิน/.test(e) && /1 ค่าไฟ 1,850 สมเจต การไฟฟ้า/.test(e) && /รวมจ่ายเป็นเงินทั้งสิ้น 1,850/.test(e), 'expense A4 sheet row: ' + e)
  must((await et.locator('tbody tr').count()) === 25, 'voucher sheet keeps 25 locked rows')
  await page.screenshot({ path: 'shots/entry-expense.png', fullPage: true })
  await page.getByRole('tab', { name: /รวมจ่าย/ }).click()
  const pt = (await page.locator('.a4page').last().innerText()).replace(/\n/g, ' ')
  must(/ค่าไฟ[^0-9]*1\s+1,850\.00/.test(pt), 'summary row per item: ' + pt)
  // เพิ่มรายการที่ ตั้งค่า → โผล่ในตัวเลือกของหน้าบันทึกทันที · ลบที่ ตั้งค่า → หายไป
  await page.goto(`http://localhost:${PORT}/#/settings`)
  await page.evaluate(() => document.querySelectorAll('details.fold').forEach((d) => { d.open = true }))
  await page.getByLabel('ชื่อรายการจ่ายใหม่').fill('ค่าน้ำมันรถสีขาว')
  await page.getByLabel('ชื่อรายการจ่ายใหม่').locator('xpath=following-sibling::button').click()
  await page.getByLabel('ชื่อประเภทถวายใหม่').fill('ถวายพิเศษ')
  await page.getByLabel('ชื่อประเภทถวายใหม่').locator('xpath=following-sibling::button').click()
  await page.goto(`http://localhost:${PORT}/#/`)
  await page.getByRole('tab', { name: /🔴 จ่าย/ }).click(); await page.getByRole('tab', { name: /บันทึกด้วยมือ/ }).click()
  must((await page.locator('#me-item option').allInnerTexts()).includes('ค่าน้ำมันรถสีขาว'), 'item added in settings appears in the entry list')
  await page.getByRole('tab', { name: /💚 รับ/ }).click(); await page.getByRole('tab', { name: /บันทึกด้วยมือ/ }).click()
  must((await page.locator('#mi-type option').allInnerTexts()).includes('ถวายพิเศษ'), 'type added in settings appears in the entry list')
  must(await page.getByText('＋ เพิ่มประเภทใหม่').count() === 0, 'no add-new option on the entry page')
  // ตั้งค่า: ล้างรายการเก่า/กลับเป็นรายการตามใบ
  page.on('dialog', (d) => d.accept())
  await page.goto(`http://localhost:${PORT}/#/settings`)
  await page.evaluate(() => document.querySelectorAll('details.fold').forEach((d) => { d.open = true }))
  must(await page.getByText('🧾 รายการจ่าย (12 รายการ)').isVisible(), 'expense list shows 11 + the one added')
  await page.getByRole('button', { name: 'ลบ ค่าน้ำมันรถสีขาว' }).click()
  await page.getByText('🧾 รายการจ่าย (11 รายการ)').waitFor()
  await page.getByLabel('ชื่อรายการจ่ายใหม่').fill('ค่าทดสอบ')
  await page.getByLabel('ชื่อรายการจ่ายใหม่').locator('xpath=following-sibling::button').click()
  await page.getByText('🧾 รายการจ่าย (12 รายการ)').waitFor()
  await page.getByRole('button', { name: '↺ คืนเป็นรายการตามใบ' }).last().click()
  await page.getByText('🧾 รายการจ่าย (11 รายการ)').waitFor()
  must((await page.getByRole('button', { name: /^ลบ ถวายพิเศษ$/ }).count()) === 1, 'custom income type has a delete button')
  await page.getByRole('button', { name: '↺ คืนเป็นรายการตามใบ' }).first().click()
  await page.waitForTimeout(300)
  must((await page.getByRole('button', { name: /^ลบ ถวายพิเศษ$/ }).count()) === 0, 'reset removes custom income types')
  must(errors.length === 0, 'page errors: ' + errors.join('|'))
  console.log('ENTRY OK')
} catch (e) { await page.screenshot({ path: 'shots/entry-fail.png', fullPage: true }); console.error(e.message); process.exitCode = 1 } finally { await browser.close(); server.kill() }
