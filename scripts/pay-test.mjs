// ทดสอบโหมดจ่าย: 1 บันทึกด้วยมือ · 2 วางบิล · 3 สำรองจ่าย · 4 รวมจ่าย → สรุปหักลบอัตโนมัติ: npm run build && node scripts/pay-test.mjs
import { chromium } from 'playwright'
import { spawn } from 'node:child_process'
import fs from 'node:fs'
const PORT = 4177
const server = spawn('npx', ['vite', 'preview', '--port', String(PORT), '--strictPort'], { stdio: 'ignore' })
await new Promise((r) => setTimeout(r, 2500))
const exe = fs.existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : undefined
const browser = await chromium.launch(exe ? { executablePath: exe } : {})
const page = await (await browser.newContext({ viewport: { width: 390, height: 800 }, locale: 'th-TH', acceptDownloads: true })).newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
const today = (() => { const d = new Date(); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}` })()
const must = (c, m) => { if (!c) throw new Error('FAIL: ' + m) }
try {
  await page.goto(`http://localhost:${PORT}/#/`); await page.waitForLoadState('networkidle')
  // ตั้งรหัส Gemini (จำลอง) แล้วให้ระบบอ่านบิล
  await page.goto(`http://localhost:${PORT}/#/settings`)
  await page.evaluate(() => document.querySelectorAll('details.fold').forEach((d) => { d.open = true }))
  await page.getByLabel('รหัส Gemini API').fill('TEST-KEY-1234')
  await page.getByRole('button', { name: 'บันทึกรหัส' }).click()
  await page.route('**/generativelanguage.googleapis.com/**', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ candidates: [{ content: { parts: [{ text: JSON.stringify({ kind: 'invoice', vendor: 'การประปา', date: today, total: 2000, summary: 'ค่าน้ำประปา ก.ย. 69', category: '11', ref: 'INV-77' }) }] } }] }) }))
  await page.goto(`http://localhost:${PORT}/#/`); await page.waitForLoadState('networkidle')
  await page.getByRole('tab', { name: '🔴 จ่าย' }).click()
  for (const n of ['บันทึกด้วยมือ', 'วางบิล', 'สำรองจ่าย', 'รวมจ่าย']) must(await page.getByRole('tab', { name: new RegExp(n) }).isVisible(), 'pay sub tab ' + n)
  const total = async () => { await page.getByRole('tab', { name: /รวมจ่าย/ }).click(); return (await page.locator('.a4page').last().innerText()).replace(/\n/g, ' ') }
  const save = () => page.getByRole('button', { name: 'บันทึก', exact: true }).click()

  // 1 บันทึกด้วยมือ: ค่าไฟฟ้า 1,850 โอน (หมวด 3.1)
  await page.getByRole('tab', { name: /บันทึกด้วยมือ/ }).click()
  {
    const [d1] = await Promise.all([page.waitForEvent('download', { timeout: 30000 }), page.getByRole('button', { name: /ดาวน์โหลดใบเบิก-จ่ายเงินสด/ }).click()])
    must((await import('node:fs')).default.readFileSync(await d1.path()).subarray(0, 5).toString() === '%PDF-', 'blank cash voucher PDF downloads from tab 1')
  }
  await page.getByRole('button', { name: /บันทึกแบบละเอียด/ }).click()
  must((await page.locator('#e-cat option').count()) === 12, 'detailed form lists the 11 items + blank')
  await page.locator('#e-cat').selectOption('xq-10')
  must((await page.locator('#e-desc').inputValue()) === 'ค่าไฟ', 'desc auto-filled from the category')
  await page.locator('#e-amt').fill('1850')
  await page.getByRole('button', { name: 'โอนเงิน' }).click()
  await save()
  must(/รวมจ่ายเป็นเงินทั้งสิ้น\s+1,850/.test((await page.locator('.a4page').first().innerText()).replace(/\n/g, ' ')), 'voucher sheet total shows the saved amount')

  // 2 วางบิล: ถ่าย/เลือกรูปบิล → ระบบอ่าน (วันที่ ยอด ร้าน หมวด) → ตรวจ → ยืนยัน (ยังไม่จ่าย 2,000)
  await page.getByRole('tab', { name: /วางบิล/ }).click()
  must(await page.locator('#e-amt').count() === 0, 'no fields before choosing a bill photo')
  must((await page.getByLabel('ถ่ายรูปบิล').getAttribute('capture')) === 'environment', 'camera button for bills')
  await page.getByLabel('แนบไฟล์บิล').setInputFiles('public/icon-512.png')
  await page.locator('#e-amt').waitFor({ timeout: 60000 })
  must((await page.locator('#e-cat').inputValue()) === 'xq-11', 'category suggested from the bill: ' + (await page.locator('#e-cat').inputValue()))
  must((await page.locator('#e-desc').inputValue()) === 'ค่าน้ำประปา ก.ย. 69', 'description read from the bill')
  must((await page.locator('#e-who').inputValue()) === 'การประปา', 'vendor read from the bill')
  must((await page.locator('#e-amt').inputValue()).replace(/[^\d.]/g, '') === '2000.00', 'amount read from the bill: ' + (await page.locator('#e-amt').inputValue()))
  must((await page.locator('#e-date').inputValue()) === today, 'date read from the bill')
  await save()
  must(await page.getByText('ค้างจ่าย').first().isVisible(), 'open bill shows as pending')
  await page.getByRole('tab', { name: /บันทึกด้วยมือ/ }).click()
  const sheetTxt = (await page.getByLabel('ใบเบิก-จ่ายเงินสด (A4)').first().innerText()).replace(/\n/g, ' ')
  must(/วางบิล · รอจ่าย/.test(sheetTxt) && /การประปา/.test(sheetTxt) && /ผู้วางบิล/.test(sheetTxt) && /2,000/.test(sheetTxt), 'open bill appears on the voucher sheet (remark + biller column): ' + sheetTxt)
  // รายชื่อผู้วางบิล: เพิ่มชื่อแล้วเลือกใช้ได้
  await page.locator('summary', { hasText: /เพิ่ม \/ .*ลบ ชื่อ/ }).first().click()
  await page.getByLabel('ชื่อชื่อใหม่').fill('สมชาย ใจดี')
  await page.getByLabel('ชื่อชื่อใหม่').locator('xpath=ancestor::details[1]').getByRole('button', { name: '＋ เพิ่ม' }).click()
  must((await page.locator('#me-biller').inputValue()) === 'สมชาย ใจดี', 'new name added to the reusable list and selected')
  must(await page.getByLabel('แนบไฟล์สลิปหรือบิล').count() === 1, 'manual tab has attach-slip button')
  let t = await total()
  must(/รวมทั้งสิ้น\s+0\s+0\.00\s+1\s+1,850\.00\s+2,000\.00\s+3,850\.00/.test(t), 'open bill counts immediately as pending (ค้างจ่าย): ' + t)
  must(await page.getByText(/ต้องเตรียมเบิก 2,000\.00/).isVisible(), 'pending note shows the amount to prepare for withdrawal')
  // สรุป: รายจ่ายค้างจ่ายถูกหักลบทันที (ยังไม่มีรายรับ)
  await page.getByRole('tab', { name: /สรุป/ }).click()
  await page.locator('.sumrow').first().click()
  const st0 = (await page.locator('.a4page').first().innerText()).replace(/\n/g, ' ')
  must(/รวมรายจ่าย\s+3,850/.test(st0), 'summary notice shows the unpaid bill as expense: ' + st0)
  must(/จ่ายมากกว่ารับ\s+[-−]3,850/.test(st0), 'summary net deducts pending too: ' + st0)
  await page.getByRole('tab', { name: '🔴 จ่าย' }).click()
  await total()
  await page.screenshot({ path: 'shots/pay-total.png', fullPage: true })
  await page.getByRole('tab', { name: /วางบิล/ }).click()
  await page.getByRole('button', { name: '✓ จ่ายแล้ว' }).click()
  await page.getByRole('button', { name: 'ยืนยัน' }).click()
  t = await total()
  must(/ค่าไฟ\s+1\s+1,850\.00\s+1,850\.00/.test(t) && /ค่าน้ำ\s+1\s+2,000\.00/.test(t), 'paid bill counted per item (ค่าน้ำ cash 2,000 + ค่าไฟ transfer 1,850): ' + t)

  // 3 สำรองจ่าย: ผู้สำรองจ่าย คืนเงินแล้ว 600 เงินสด (หมวด 11.4)
  await page.getByRole('tab', { name: /สำรองจ่าย/ }).click()
  must((await page.locator('.capbar__row .act-btn').count()) === 3, 'advance tab has three buttons: download, attach, camera')
  must(await page.getByRole('button', { name: /ดาวน์โหลดใบเปล่า/ }).isVisible(), 'advance tab offers the blank voucher')
  await page.getByRole('button', { name: /กรอกเอง \(ไม่มีรูป\)/ }).click()
  await page.locator('#e-cat').selectOption('xq-6')
  await page.locator('#e-amt').fill('600')
  await page.locator('#e-who').fill('สมเจต')
  await page.locator('#e-status').selectOption('paid')
  await save()
  t = await total()
  must(/รวมทั้งสิ้น\s+2\s+2,600\.00\s+1\s+1,850\.00\s+0\.00\s+4,450\.00/.test(t), 'grand total (3 channels): ' + t)

  await page.getByRole('tab', { name: /วางบิล/ }).click()
  await page.screenshot({ path: 'shots/pay.png', fullPage: true })
  // แก้ไข / ลบ
  await page.getByRole('tab', { name: /บันทึกด้วยมือ/ }).click()
  await page.evaluate(() => document.querySelectorAll('details.editlist').forEach((d) => { d.open = true }))
  await page.getByRole('button', { name: 'แก้ไขรายการนี้' }).first().click()
  await page.locator('#e-amt').fill('1900')
  await save()
  must(/4,500\.00/.test(await total()), 'edit updates the total')
  await page.getByRole('tab', { name: /บันทึกด้วยมือ/ }).click()
  page.once('dialog', (d) => d.accept())
  await page.evaluate(() => document.querySelectorAll('details.editlist').forEach((d) => { d.open = true }))
  await page.getByRole('button', { name: 'ลบรายการนี้' }).first().click()
  await page.waitForTimeout(300)
  must(/รวมทั้งสิ้น\s+2\s+2,600\.00\s+0\s+0\.00\s+0\.00\s+2,600\.00/.test(await total()), 'delete removes it from the total')

  // 3 กรอบสรุปประจำสัปดาห์ใต้ตารางใบเบิก
  await page.getByRole('tab', { name: /บันทึกด้วยมือ/ }).click()
  const box = (await page.getByLabel('สรุปประจำสัปดาห์').first().innerText()).replace(/\n/g, ' ')
  must(/สรุปรับประจำสัปดาห์/.test(box) && /สรุปจ่ายประจำสัปดาห์/.test(box) && /เงินหมุนเวียนทั้งหมดปัจจุบัน/.test(box) && /กองทุน/.test(box), 'three summary boxes: ' + box)
  // สรุป: หักลบกับรายรับอัตโนมัติ (ไม่มีรายรับ → คงเหลือติดลบเท่ารายจ่าย)
  await page.getByRole('tab', { name: /สรุป/ }).click()
  await page.locator('.sumrow').first().click()
  const st = (await page.locator('.a4page').first().innerText()).replace(/\n/g, ' ')
  must(/รวมรายจ่าย\s+2,600/.test(st), 'summary shows expenses from the pay tabs: ' + st)
  must(/จ่ายมากกว่ารับ\s+[-−]2,600/.test(st), 'summary net deducts expenses: ' + st)
  must(errors.length === 0, 'page errors: ' + errors.join('|'))
  console.log('PAY OK')
} catch (e) { await page.screenshot({ path: 'shots/pay-fail.png', fullPage: true }); console.error(e.message); process.exitCode = 1 } finally { await browser.close(); server.kill() }
