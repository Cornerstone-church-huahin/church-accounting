// บันทึกการประชุม ส่วนที่ 1: รายชื่อคณะธรรมกิจ ร่วม/ลา/ขาด + ผู้สังเกตการณ์ → ไปส่วนที่ 2 (วาระ)
import { chromium } from 'playwright'
import { spawn } from 'node:child_process'
import fs from 'node:fs'
const PORT = 4461
const server = spawn('npx', ['vite', 'preview', '--port', String(PORT), '--strictPort'], { stdio: 'ignore' })
const must = (c, m) => { if (!c) throw new Error('FAIL: ' + m) }
try {
  await new Promise((r) => setTimeout(r, 2500))
  const b = await chromium.launch(fs.existsSync('/opt/pw-browsers/chromium') ? { executablePath: '/opt/pw-browsers/chromium' } : {})
  const p = await (await b.newContext({ viewport: { width: 390, height: 900 }, locale: 'th-TH' })).newPage()
  const errors = []; p.on('pageerror', (e) => errors.push(String(e)))
  await p.addInitScript(() => {
    if (localStorage.getItem('seeded')) return; localStorage.setItem('seeded', '1')
    localStorage.setItem('acct.sync.v1', JSON.stringify({ repo: 'x/y', token: 'fake', name: 'แอดมิน' }))
    localStorage.setItem('acct.me.v1', JSON.stringify({ id: 'ad1' }))
    localStorage.setItem('acct.members.v1', JSON.stringify([{ id: 'ad1', name: 'แอดมิน', role: 'admin', joined: 1, updated: 1 }]))
    localStorage.setItem('acct.mc.cur', 'mt1')
    localStorage.setItem('acct.meetings.v1', JSON.stringify([{ minutesDone: {at:1}, rosterDone: {at:1}, agendaDone: {at:1}, closeDone: {at:1}, closed: {time:'15:00'}, id: 'mt1', name: 'ประชุมคณะธรรมกิจ', no: 1, year: 2026, type: 'ปกติ', date: '2026-11-01', time: '13:00', place: '', chair: 'ประธาน ก', secretary: 'เลขา ข', people: [], agenda: [{ id: 'a1', title: 'กล่าวต้อนรับ', group: 'แจ้งเพื่อทราบ', purpose: 'ทราบ' }, { id: 'a1c', title: 'ทดสอบ', group: 'แจ้งเพื่อทราบ', purpose: 'ทราบ', parentId: 'a1' }], updated: 1 }]))
  })
  await p.route('**/api.github.com/**', (r) => r.request().method() === 'PUT' ? r.fulfill({ status: 201, contentType: 'application/json', body: JSON.stringify({ content: { sha: 'abc' } }) }) : r.fulfill({ status: 404, body: '{}' }))
  await p.goto(`http://localhost:${PORT}/#/meeting/1/4/7`); await p.reload()
  const dots = p.getByRole('navigation', { name: 'ลำดับรายงานการประชุม' }).getByRole('button')
  await dots.first().waitFor({ timeout: 10000 })
  must(await dots.count() === 4 && await dots.nth(1).isDisabled(), '4 parts, later locked')
  await p.getByRole('button', { name: /บันทึกฉบับและส่งให้ประธานตรวจ/ }).click()
  await p.waitForTimeout(500)
  must(!(await dots.nth(1).isDisabled()), 'part 2 unlocked after send')
  await dots.nth(1).click()
  await p.getByRole('button', { name: /บันทึกว่าประธานตรวจฉบับนี้แล้ว/ }).click()
  await p.getByLabel(/ลงนามบนกระดาษแล้ว/).check()
  await p.waitForTimeout(500)
  must(!(await dots.nth(2).isDisabled()), 'part 3 unlocked after chair review+signed')
  await dots.nth(2).click()
  await p.locator('#rf-r').selectOption('รับรองโดยไม่แก้ไข')
  await p.locator('#rf-d').fill('2026-12-06')
  await p.waitForTimeout(500)
  must(!(await dots.nth(3).isDisabled()), 'part 4 unlocked after approval')
  await dots.nth(3).click()
  await p.getByRole('button', { name: /เก็บเข้าแฟ้ม และส่งเข้าคลังเอกสาร/ }).click()
  await p.getByText(/เก็บเข้าแฟ้มแล้ว/).waitFor({ timeout: 30000 })
  const ms = JSON.parse(await p.evaluate(() => localStorage.getItem('acct.meetings.v1')))
  must(!!ms[0].archived && ms[0].reportDocId, 'archived + doc id saved')
  const docs = JSON.parse(await p.evaluate(() => localStorage.getItem('acct.doclib.v1') ?? '[]'))
  must(docs.some((d) => d.category === 'รายงานการประชุม' && d.file?.path), 'library item created: ' + JSON.stringify(docs).slice(0, 120))
  must(errors.length === 0, 'no page errors ' + errors)
  console.log('OK report flow')
  await b.close()
} finally { server.kill() }
