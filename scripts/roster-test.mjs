// บันทึกการประชุม ส่วนที่ 1: รายชื่อคณะธรรมกิจ ร่วม/ลา/ขาด + ผู้สังเกตการณ์ → ไปส่วนที่ 2 (วาระ)
import { chromium } from 'playwright'
import { spawn } from 'node:child_process'
import fs from 'node:fs'
const PORT = 4397
const server = spawn('npx', ['vite', 'preview', '--port', String(PORT), '--strictPort'], { stdio: 'ignore' })
const must = (c, m) => { if (!c) throw new Error('FAIL: ' + m) }
try {
  await new Promise((r) => setTimeout(r, 2500))
  const b = await chromium.launch(fs.existsSync('/opt/pw-browsers/chromium') ? { executablePath: '/opt/pw-browsers/chromium' } : {})
  const p = await (await b.newContext({ viewport: { width: 390, height: 900 }, locale: 'th-TH' })).newPage()
  const errors = []; p.on('pageerror', (e) => errors.push(String(e)))
  await p.addInitScript(() => {
    if (localStorage.getItem('seeded')) return; localStorage.setItem('seeded', '1')
    localStorage.setItem('acct.sync.v1', JSON.stringify({ repo: 'x/y', token: 'fake', name: 'แอดมิน' }))
    localStorage.setItem('acct.me.v1', JSON.stringify({ id: 'ad1' }))
    localStorage.setItem('acct.members.v1', JSON.stringify([{ id: 'ad1', name: 'แอดมิน', role: 'admin', joined: 1, updated: 1 }]))
    localStorage.setItem('acct.mc.cur', 'mt1')
    localStorage.setItem('acct.meetings.v1', JSON.stringify([{ id: 'mt1', name: 'ประชุมคณะธรรมกิจ', no: 1, year: 2026, type: 'ปกติ', date: '2026-11-01', time: '13:00', place: '', chair: '', secretary: '', people: [], agenda: [{ id: 'a1', title: 'กล่าวต้อนรับ', group: 'แจ้งเพื่อทราบ', purpose: 'ทราบ' }], updated: 1 }]))
  })
  await p.route('**/api.github.com/**', (r) => r.fulfill({ status: 404, body: '{}' }))
  await p.goto(`http://localhost:${PORT}/#/meeting/1/4/6`); await p.reload()
  const list = p.getByRole('list', { name: 'รายชื่อคณะธรรมกิจ' })
  await list.waitFor({ timeout: 10000 })
  must(await list.getByRole('listitem').count() === 12, '12 committee members seeded from the standing roster')
  must(/ศิษยาภิบาลคริสตจักร/.test(await list.getByRole('listitem').first().innerText()) && /รินรดา/.test(await list.getByRole('listitem').nth(11).innerText()), 'default 12 names with positions')
  // ⚙️ ตั้งค่ารายชื่อหลัก (ป๊อปอัพ): เพิ่มกรรมการ → บันทึก → ใช้ได้ทั้งการประชุมนี้และครั้งต่อไป
  await p.getByRole('button', { name: 'เพิ่มกรรมการ', exact: true }).click()
  const dlg = p.getByRole('dialog', { name: 'ตั้งค่ารายชื่อคณะกรรมการหลัก' })
  p.once('dialog', (d) => d.accept())
  await dlg.getByRole('button', { name: /ใส่รายชื่อ 12 คนตามรายงานเดิม/ }).click()
  must(await dlg.locator('input[id^="su-n-"]').count() === 12, 'one-tap fills the 12 names')
  await p.getByRole('button', { name: 'เพิ่มกรรมการ', exact: true }).waitFor().catch(() => {})
  await dlg.getByRole('button', { name: /^เลื่อน .* ลง$/ }).first().click()   // เลื่อนคนแรกลง → อันดับ 1 เปลี่ยนเป็นคนที่สอง
  await dlg.getByRole('button', { name: '＋ เพิ่มกรรมการ' }).click()
  await dlg.locator('input[id^="su-r-"]').last().fill('กรรมการใหม่'); await dlg.locator('input[id^="su-n-"]').last().fill('คนที่สิบสาม')
  await dlg.getByRole('button', { name: 'บันทึกรายชื่อ' }).click()
  await list.getByRole('listitem').nth(12).waitFor({ timeout: 5000 })
  must(/พิชิต/.test(await list.getByRole('listitem').first().innerText()), 'moved down in the popup → numbering follows')
  must(await list.getByRole('listitem').count() === 13, 'new member appears in the attendance list')
  const cm = JSON.parse(await p.evaluate(() => localStorage.getItem('acct.committee.v1')))
  must(cm.filter((x) => !x.deleted).length === 13, 'standing roster saved for all meetings')
  const go = p.getByRole('button', { name: /บันทึกใบลงชื่อ — ไปส่วนที่ 2/ })
  const dots = p.getByRole('navigation', { name: 'ลำดับการบันทึกการประชุม' }).getByRole('button')
  must(await dots.count() === 4 && await dots.nth(1).isDisabled() && await dots.nth(0).innerText() === '1', 'bottom bar shows parts 1-4, later parts locked')
  must(await go.isDisabled(), 'cannot continue until everyone is marked')
  await p.getByRole('button', { name: /ติ๊ก “ร่วม” ให้ทุกคน/ }).click()
  await list.getByRole('listitem').nth(1).getByRole('button', { name: 'ลา', exact: true }).click()
  await list.getByRole('listitem').nth(2).getByRole('button', { name: 'ขาด', exact: true }).click()
  await p.getByRole('button', { name: /เพิ่มผู้เข้าร่วม \/ ผู้สังเกตการณ์/ }).click()
  await p.getByRole('list', { name: /ผู้เข้าร่วมประชุมและผู้สังเกตการณ์/ }).getByRole('listitem').first().waitFor()
  const gl = p.getByRole('list', { name: /ผู้เข้าร่วมประชุมและผู้สังเกตการณ์/ })
  await gl.getByRole('listitem').first().locator('input').first().fill('สมชาย'); await gl.getByRole('listitem').first().locator('input').first().blur()
  await p.getByRole('button', { name: /เพิ่มผู้เข้าร่วม \/ ผู้สังเกตการณ์/ }).click()
  await gl.getByRole('listitem').nth(1).locator('input').first().fill('สมชาย'); await gl.getByRole('listitem').nth(1).locator('input').first().blur()
  await p.getByText(/มีในรายชื่อผู้เข้าร่วมแล้ว/).waitFor({ timeout: 5000 })
  must(/ผู้ร่วมประชุมทั้งหมด \d+ คน/.test(await p.locator('body').innerText()), 'total attendees shown')
  must(await go.isEnabled(), 'enabled when all marked')
  await go.click()
  await p.getByText(/ส่วนที่ 2 · บันทึกแล้ว/).waitFor({ timeout: 5000 })
  must((await dots.nth(0).innerText()) === '✓' && await dots.nth(1).isEnabled(), 'part 1 turns green and part 2 unlocks')
  must(await p.getByText('กล่าวต้อนรับ').count() >= 1, 'part 2 shows agenda minutes')
  // ส่วนที่ 2: แก้ชื่อวาระ · เพิ่มวาระ · ลบ · บันทึกเสร็จ → ส่งไปรายงาน
  await p.locator('input[id^="mt-a1"]').fill('กล่าวต้อนรับ (แก้แล้ว)'); await p.locator('input[id^="mt-a1"]').blur()
  await p.getByRole('button', { name: '＋ เพิ่มวาระ' }).click()
  await p.getByText('วาระใหม่').first().waitFor({ timeout: 5000 })
  p.once('dialog', (d) => d.accept())
  await p.getByRole('button', { name: /^ลบวาระ วาระใหม่/ }).click()
  await p.waitForTimeout(300)
  await p.getByRole('button', { name: /เสร็จส่วนที่ 2/ }).click()
  await p.locator('#mt-close-time').fill('15:00'); await p.locator('#mt-close-time').blur()
  await p.getByRole('button', { name: /เสร็จส่วนที่ 3/ }).click()
  await p.getByText('ส่วนที่ 4 · สรุปก่อนส่งไปรายงาน').waitFor({ timeout: 5000 })
  await p.getByRole('button', { name: /บันทึกเสร็จ — ส่งไปรายงานการประชุม/ }).click()
  await p.waitForURL(/#\/meeting\/1\/4\/7/)
  const ms = JSON.parse(await p.evaluate(() => localStorage.getItem('acct.meetings.v1')))
  must(ms[0].minutesDone && ms[0].agenda.length === 1 && /แก้แล้ว/.test(ms[0].agenda[0].title), 'agenda edited and minutes marked done: ' + JSON.stringify(ms[0].agenda))
  const pe = ms[0].people
  must(pe.filter((x) => x.kind === 'กรรมการ').length === 13 && pe.filter((x) => x.att === 'ลา').length === 1 && pe.filter((x) => x.att === 'ไม่มา').length === 1, 'attendance saved onto the meeting')
  // ยังไม่เคยตั้งค่า: ป๊อปอัพตั้งค่าเด้งขึ้นก่อน
  const p2 = await (await b.newContext({ viewport: { width: 390, height: 900 }, locale: 'th-TH' })).newPage()
  await p2.addInitScript(() => {
    localStorage.setItem('acct.sync.v1', JSON.stringify({ repo: 'x/y', token: 'fake', name: 'แอดมิน' })); localStorage.setItem('acct.me.v1', JSON.stringify({ id: 'ad1' }))
    localStorage.setItem('acct.members.v1', JSON.stringify([{ id: 'ad1', name: 'แอดมิน', role: 'admin', joined: 1, updated: 1 }])); localStorage.setItem('acct.mc.cur', 'mt1')
    localStorage.setItem('acct.committee.v1', JSON.stringify(Array.from({ length: 12 }, (_, i) => ({ id: 'cm-d' + String(i + 1).padStart(2, '0'), name: 'x', role: '', order: i, deleted: true, updated: 5 }))))
    localStorage.setItem('acct.meetings.v1', JSON.stringify([{ id: 'mt1', name: 'x', no: 1, year: 2026, type: 'ปกติ', date: '', time: '', place: '', chair: '', secretary: '', people: [], agenda: [], updated: 1 }]))
  })
  await p2.route('**/api.github.com/**', (r) => r.fulfill({ status: 404, body: '{}' }))
  await p2.goto(`http://localhost:${PORT}/#/meeting/1/4/6`)
  await p2.getByRole('dialog', { name: 'ตั้งค่ารายชื่อคณะกรรมการหลัก' }).waitFor({ timeout: 10000 })
  must(errors.length === 0, 'page errors: ' + errors.join('|'))
  await b.close(); console.log('roster-test OK')
} catch (e) { console.error(String(e.message || e).slice(0, 700)); process.exitCode = 1 } finally { server.kill() }
