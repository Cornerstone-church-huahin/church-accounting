// งานอภิบาล › ตารางเยี่ยม: การ์ด 7 วัน (อาทิตย์ นมัสการ · จันทร์ วันหยุด) · บันทึกการเยี่ยม (สมาชิก เหตุผล ผู้เยี่ยมลงชื่อ) · รายงานสัปดาห์ A4/PDF ย้อนสัปดาห์ได้ (ข้อมูลสมมติเท่านั้น)
import { chromium } from 'playwright'
import { spawn } from 'node:child_process'
import fs from 'node:fs'
const PORT = 4192
const server = spawn('npx', ['vite', 'preview', '--port', String(PORT), '--strictPort'], { stdio: 'ignore' })
await new Promise((r) => setTimeout(r, 2500))
const exe = fs.existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : undefined
const browser = await chromium.launch(exe ? { executablePath: exe } : {})
const page = await (await browser.newContext({ viewport: { width: 390, height: 900 }, locale: 'th-TH' })).newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e))); page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()) })
const must = (c, m) => { if (!c) throw new Error('FAIL: ' + m) }
try {
  await page.goto(`http://localhost:${PORT}/#/`)
  await page.evaluate(() => {
    const members = Array.from({ length: 6 }, (_, i) => ({ id: `t${i}`, name: `ทดสอบ${i} สมมติ`, nick: `ช${i}`, status: i % 2 ? '3.สมาชิกสำรอง' : '1.สมบูรณ์  ( 1 )', updated: 1 }))
    localStorage.setItem('acct.church-members.v1', JSON.stringify(members))
    localStorage.setItem('acct.work-teams.v1', JSON.stringify([{ id: 'team-4', n: 4, people: [{ role: '1', name: 'คศ.กฤต' }, { role: '2', name: 'คศ.พิชิต' }], updated: 1 }]))
  })
  await page.goto(`http://localhost:${PORT}/#/meeting/4/2`); await page.reload(); await page.waitForLoadState('networkidle')
  await page.getByRole('heading', { name: /ตารางเยี่ยม/, level: 1 }).waitFor({ timeout: 8000 })
  const days = page.locator('.pvday')
  must(await days.count() === 7, 'seven day cards')
  must(/อาทิตย์/.test(await days.nth(0).innerText()) && /นมัสการ/.test(await days.nth(0).innerText()), 'Sunday auto: worship')
  must(/จันทร์/.test(await days.nth(1).innerText()) && /วันหยุด/.test(await days.nth(1).innerText()), 'Monday auto: day off')
  must(await page.getByRole('button', { name: /บันทึกการเยี่ยม/ }).count() === 5, 'Tue–Sat have add buttons')
  const tue = days.nth(2)
  await tue.getByRole('button', { name: /บันทึกการเยี่ยม/ }).click()
  const dlg = page.getByRole('dialog')
  await dlg.getByRole('button', { name: 'บันทึก', exact: true }).click()
  must(/เลือกสมาชิกที่ไปเยี่ยม/.test(await dlg.innerText()), 'member required')
  await dlg.locator('#pv-q').fill('ทดสอบ3')
  await dlg.getByRole('button', { name: /ทดสอบ3 สมมติ/ }).click()
  await dlg.getByRole('button', { name: 'บันทึก', exact: true }).click()
  must(/ลงชื่อผู้เยี่ยม/.test(await dlg.innerText()), 'visitor signature required')
  await dlg.locator('#pv-by').selectOption('คศ.กฤต')
  await dlg.getByLabel(/เหตุผล/).fill('ป่วย ไม่ได้มานมัสการ')
  must(/ยังไม่ได้แนบรูป/.test(await dlg.innerText()), 'photo hint before attaching')
  const png = await page.evaluate(async () => { const c = document.createElement('canvas'); c.width = 40; c.height = 30; const g = c.getContext('2d'); g.fillStyle = '#3a7'; g.fillRect(0, 0, 40, 30); g.fillStyle = '#fff'; g.fillRect(8, 8, 14, 10); const b = await new Promise((r) => c.toBlob(r, 'image/png')); return [...new Uint8Array(await b.arrayBuffer())] }).then((a) => Buffer.from(a))
  await dlg.getByLabel('ถ่ายรูปการเยี่ยม').setInputFiles({ name: 'v1.png', mimeType: 'image/png', buffer: png })
  await dlg.getByRole('button', { name: 'ลบรูปที่ 1' }).waitFor({ timeout: 15000 })
  await dlg.getByLabel('เลือกรูปการเยี่ยมจากเครื่อง').setInputFiles({ name: 'v2.png', mimeType: 'image/png', buffer: png })
  await dlg.getByRole('button', { name: 'ลบรูปที่ 2' }).waitFor({ timeout: 15000 })
  must(await dlg.getByLabel('ถ่ายรูปการเยี่ยม').count() === 0 && /แนบแล้ว 2 รูป/.test(await dlg.innerText()), 'max two photos: add buttons gone')
  await dlg.getByRole('button', { name: 'บันทึก', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'detached' })
  must(await tue.locator('.pvvisit__pic img').count() === 1 && /\+1/.test(await tue.locator('.pvvisit__pic').innerText()), 'card shows the first photo with +1 badge')
  const t = await tue.innerText()
  must(/ทดสอบ3 สมมติ/.test(t) && /ป่วย ไม่ได้มานมัสการ/.test(t) && /ผู้เยี่ยม คศ.กฤต/.test(t), 'card shows member, reason and signed visitor: ' + t)
  must(/เยี่ยมแล้ว 1 ครั้ง · 1 คน/.test(await page.locator('.pvisits p[role=status]').innerText()), 'week count')
  // เยี่ยมคนเดิมอีกวัน โดย คศ.พิชิต (ผู้เยี่ยมจำค่าล่าสุดไว้ แต่เปลี่ยนได้)
  await days.nth(3).getByRole('button', { name: /บันทึกการเยี่ยม/ }).click()
  await page.getByRole('dialog').locator('#pv-q').fill('ช1')
  await page.getByRole('dialog').getByRole('button', { name: /ทดสอบ1 สมมติ/ }).click()
  await page.getByRole('dialog').locator('#pv-by').selectOption('คศ.พิชิต')
  await page.getByRole('dialog').getByRole('button', { name: 'บันทึก', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'detached' })
  must(await days.nth(3).locator('.pvvisit__nopic').count() === 1, 'visit without photo shows the camera placeholder')
  // แก้ไข/ลบ
  await tue.getByRole('button', { name: /แก้ไขการเยี่ยม/ }).click()
  await page.getByRole('dialog').getByLabel(/รายละเอียดการเยี่ยม/).fill('อธิษฐานร่วมกัน')
  await page.getByRole('dialog').getByRole('button', { name: 'บันทึก', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'detached' })
  await page.screenshot({ path: 'shots/visits-cards.png', fullPage: true })
  // รายงานสัปดาห์
  await page.getByRole('tab', { name: /รายงานสัปดาห์/ }).click()
  const sheet = (await page.locator('.a4page').allInnerTexts()).join('\n')
  must(/รายงานการเยี่ยมประจำสัปดาห์/.test(sheet) && /ทดสอบ3 สมมติ/.test(sheet) && /ทดสอบ1 สมมติ/.test(sheet) && /คศ\.กฤต/.test(sheet) && /คศ\.พิชิต/.test(sheet) && /อธิษฐานร่วมกัน/.test(sheet) && /รวมเยี่ยม 2 ครั้ง · 2 คน/.test(sheet), 'weekly report sheet: ' + sheet.slice(0, 300))
  must(await page.locator('.a4page [data-credit="doc"]').count() >= 1, 'document credit on the report sheet')
  const dl = page.waitForEvent('download', { timeout: 30000 })
  await page.getByRole('button', { name: /ดาวน์โหลด PDF/ }).click()
  const d = await dl; must(/^visit-report-\d{4}-\d{2}-\d{2}\.pdf$/.test(d.suggestedFilename()) && fs.readFileSync(await d.path()).subarray(0, 5).toString() === '%PDF-', 'report PDF downloads')
  await page.screenshot({ path: 'shots/visits-report.png' })
  await page.getByRole('button', { name: 'สัปดาห์ก่อน' }).click()
  must(/ไม่มีการเยี่ยมในสัปดาห์นี้/.test((await page.locator('.a4page').allInnerTexts()).join('\n')), 'previous week report is empty')
  must(await page.getByRole('button', { name: 'สัปดาห์ถัดไป' }).isEnabled(), 'can come back to this week')
  await page.getByRole('button', { name: 'สัปดาห์ถัดไป' }).click()
  await page.getByRole('tab', { name: /การ์ด 7 วัน/ }).click()
  await days.nth(2).getByRole('button', { name: /แก้ไขการเยี่ยม/ }).click()
  page.once('dialog', (x) => x.accept())
  await page.getByRole('dialog').getByRole('button', { name: 'ลบ', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'detached' })
  must(!/ทดสอบ3 สมมติ/.test(await days.nth(2).innerText()), 'delete works')
  must(errors.length === 0, 'no page errors: ' + errors.join('|'))
  console.log('visits-test OK')
} catch (e) { console.error(e.message); process.exitCode = 1 }
await browser.close(); server.kill()
