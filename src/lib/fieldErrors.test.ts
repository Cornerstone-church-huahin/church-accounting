import { describe, expect, it } from 'vitest'
import { lcs, pickField } from './fieldErrors'

const F = (label: string, empty = true) => ({ label, empty })
describe('กรอบแดง: หาช่องที่ข้อความผิดพลาดพูดถึง', () => {
  it('lcs: ข้อความร่วมยาวสุด', () => { expect(lcs('ใส่ชื่อเอกสารก่อน', 'ชื่อเอกสาร')).toBe(10); expect(lcs('abc', 'xyz')).toBe(0) })
  it('ฟอร์มเอกสาร: ใส่ชื่อ → ช่องชื่อเอกสาร · เลือกไฟล์ → ช่องไฟล์', () => {
    const fs = [F('ไฟล์เอกสารสำเร็จรูป (PDF รูป Word ฯลฯ)'), F('ชื่อเอกสาร'), F('หมวด', false), F('เลขที่ (ถ้ามี)', false), F('วันที่เอกสาร', false)]
    expect(pickField('ใส่ชื่อเอกสารก่อน', fs)).toBe(1)
    expect(pickField('เลือกไฟล์เอกสารสำเร็จรูปก่อน', fs)).toBe(0)
  })
  it('เลือกช่องว่างก่อน · เจอหลายช่องว่างได้ช่องแรก', () => {
    const fs = [F('วันที่', false), F('วันที่ครบกำหนด'), F('วันที่ชำระ')]
    expect(pickField('เลือกวันที่', fs)).toBe(1)
  })
  it('ข้อความไม่เกี่ยวกับช่อง (สิทธิ์ ออฟไลน์) ไม่ทำกรอบ', () => {
    const fs = [F('ชื่อเอกสาร'), F('จำนวนเงิน')]
    expect(pickField('สิทธิ์ของท่านบันทึกไม่ได้', fs)).toBe(-1)
    expect(pickField('ไม่มีอินเทอร์เน็ต — อัปโหลดไฟล์ไม่ได้', fs)).toBe(-1)
  })
  it('ค่าที่ไม่ถูกต้อง (ช่องไม่ว่าง) ทำกรอบเฉพาะข้อความที่บอกว่าไม่ถูกต้อง/เกิน', () => {
    const fs = [F('จำนวนเงินที่คืน', false), F('วันที่', false)]
    expect(pickField('คืนเกินยอดค้าง — จำนวนเงินที่คืนมากกว่าที่ค้างอยู่', fs)).toBe(0)
    expect(pickField('จำนวนเงินที่คืนบันทึกแล้ว', fs)).toBe(-1)
  })
  it('ใช้ได้กับหลายข้อความ: แต่ละข้อได้คนละช่อง (ไม่ซ้ำช่องเดิม)', () => {
    const fs = [F('ชื่อเอกสาร'), F('ไฟล์เอกสารสำเร็จรูป'), F('ใส่/เช็ค เลขที่เอกสาร'), F('วันที่เอกสาร/ตรงกับไฟล์', false)]
    expect(pickField('ใส่ชื่อเอกสาร', fs)).toBe(0)
    expect(pickField('เลือกไฟล์เอกสารสำเร็จรูป', fs.filter((_, i) => i !== 0))).toBe(0)
    expect(pickField('ใส่เลขที่เอกสาร', fs.filter((_, i) => i > 1))).toBe(0)
  })
  it('ช่องจำนวนเงิน: ใส่จำนวนเงิน → ช่องจำนวนเงิน (ไม่ใช่วันที่)', () => {
    expect(pickField('ใส่จำนวนเงินมากกว่า 0', [F('วันที่', false), F('จำนวนเงิน (บาท)')])).toBe(1)
  })
})
