import type { Balances } from './balances'

export interface ExplainStep { icon: string; title: string; text: string; amount?: number }

/**
 * คำอธิบายภาษาคนว่า "รวมเงินสด" มาจากไหน: เงินหมุนเวียน + กองทุนทุกกอง · เงินยืมระหว่างกระเป๋าไม่ทำให้ยอดรวมเปลี่ยน · เงินที่ยืมจากภายนอกนับเป็นเงินสดที่มีจริง (แต่ยังเป็นหนี้)
 * ext = ยอดหนี้ภายนอกที่เงินหมุนเวียนยืมมาและยังไม่คืน (สตางค์)
 */
export function explainTotal(b: Balances, ext: number, fmt: (n: number) => string): ExplainStep[] {
  const o = b.own
  const own = [`ตั้งต้น ${fmt(o.opening)}`, `+ รายรับปกติ ${fmt(o.moneyIn)}`, `− รายจ่ายปกติ ${fmt(o.moneyOut)}`]
  if (o.pending > 0) own.push(`− ค้างจ่าย ${fmt(o.pending)}`)
  if (o.borrowed > 0) own.push(`+ เงินที่ยืมมา ${fmt(o.borrowed)}`)
  if (o.lent > 0) own.push(`− ที่ให้กองทุนยืมไป ${fmt(o.lent)}`)
  const steps: ExplainStep[] = [
    { icon: '🧮', title: 'รวมเงินสดคืออะไร', text: `เงินที่คริสตจักรมีอยู่จริงทั้งหมด = เงินหมุนเวียน ${fmt(o.balance)} + เงินกองทุนทุกกอง ${fmt(b.fundTotal)} = ${fmt(b.total)} บาท`, amount: b.total },
    { icon: '🏠', title: 'เงินหมุนเวียนมาจากไหน', text: `${own.join(' ')} = ${fmt(o.balance)} บาท (เงินสำหรับบริหารงานประจำ ไม่รวมเงินถวายเข้ากองทุน)`, amount: o.balance },
    { icon: '💰', title: 'เงินกองทุนมาจากไหน', text: `${b.funds.length} กองทุน แต่ละกอง = ตั้งต้น + เงินถวายกองนั้น − ที่จ่ายจากกองนั้น รวมกัน ${fmt(b.fundTotal)} บาท · เงินถวายกองทุนนับทันทีที่รับ แม้ยังไม่ได้นำฝากธนาคาร`, amount: b.fundTotal },
  ]
  steps.push({ icon: '🔁', title: 'เงินยืมระหว่างกอง ไม่ทำให้ยอดรวมเปลี่ยน', text: 'ถ้าเงินหมุนเวียนยืมจากกองทุน ยอดหมุนเวียนเพิ่ม กองทุนลดลงเท่ากัน รวมแล้วเท่าเดิม เป็นแค่ย้ายกระเป๋า (ส่วนที่ยังเป็นหนี้แสดงที่ช่อง “หนี้ภายใน”)' })
  if (ext > 0) steps.push({ icon: '🧾', title: 'เงินยืมจากภายนอกนับรวมอยู่ด้วย', text: `เงินที่ยืมจากภายนอกที่ยังไม่คืน ${fmt(ext)} บาท อยู่ในเงินหมุนเวียนแล้ว เพราะเป็นเงินที่มีอยู่จริง แต่ยังเป็นหนี้ (ดูช่อง “หนี้ภายนอก”) เมื่อคืนเงิน ยอดรวมจะลดลงตามนั้น`, amount: ext })
  steps.push({ icon: '🏞️', title: 'ภาระที่ดินไม่นับในรวมเงินสด', text: 'ภาระที่ดินเป็นหนี้/ภาระระยะยาว ไม่ใช่เงินสดในมือ จึงไม่รวมในยอดนี้' })
  steps.push({ icon: '✅', title: 'ตรวจว่าตรงกับของจริงไหม', text: 'ยอดนี้คำนวณจากยอดตั้งต้น + รายการที่บันทึกในแอป ควรเทียบกับสมุดบัญชีธนาคาร + เงินสดจริงที่ขั้น 3 ปรับ ถ้าไม่ตรง ให้หาส่วนต่างจากรายการที่ยังไม่บันทึก' })
  return steps
}
