import { describe, expect, it } from 'vitest'
import { mergeSpeech } from './voiceInput'
describe('รวมผลเสียงพูดให้พิมพ์ (ตัดซ้ำ)', () => {
  it('ประโยคเดียวขึ้นซ้ำสองรอบ → เหลือรอบเดียว', () => {
    expect(mergeSpeech(['การทำอาหาร', 'การทำอาหาร'])).toBe('การทำอาหาร')
    expect(mergeSpeech(['การทำอาหาร การทำอาหาร'])).toBe('การทำอาหาร')
    expect(mergeSpeech(['การทำอาหารการทำอาหาร'])).toBe('การทำอาหาร')
  })
  it('ผลชั่วคราวที่ยาวขึ้นแทนที่ของเดิม ไม่ต่อท้าย', () => {
    expect(mergeSpeech(['ประชุม', 'ประชุมวัน', 'ประชุมวันอาทิตย์'])).toBe('ประชุมวันอาทิตย์')
  })
  it('ประโยคต่างกันยังต่อกันตามปกติ', () => {
    expect(mergeSpeech(['เรื่องแจ้งให้ทราบ', 'รายงานการเงิน'])).toBe('เรื่องแจ้งให้ทราบ รายงานการเงิน')
    expect(mergeSpeech(['', '  '])).toBe('')
  })
})
